#!/usr/bin/env python3
"""Generates include/cranelift.h from the extern "C" functions of src/lib.rs and include/cranelift.h.in.

The function list, parameter types and doc comments come from lib.rs, so the header cannot drift from the library; the
template holds the typedefs, enums and conveniences. `--check` fails when the committed header is not what this
produces. A parameter of a type this script does not know fails the run: add it to TYPES or ENUM_PARAMS."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BANNER = ('/* GENERATED by gen-header.py from the extern "C" functions of src/lib.rs and include/cranelift.h.in.\n'
          ' * Edit those, run `python3 gen-header.py`, and commit the result; CI runs `python3 gen-header.py --check`. */\n')

TYPES = {
    '*mut Cl': 'cl *', '*mut Fnb': 'cl_fn *', 'Val': 'cl_val', 'BlockId': 'cl_block', 'SlotId': 'cl_slot',
    'SigId': 'cl_sig', 'Func': 'cl_func', 'Data': 'cl_data', 'Ovf': 'cl_ovf_result',
    '*const c_char': 'const char *', '*const *const c_char': 'const char *const *', '*const ClReloc': 'const cl_reloc *',
    '*const ClCodeRange': 'const cl_code_range *', '*const Val': 'const cl_val *', '*mut Val': 'cl_val *',
    '*const BlockId': 'const cl_block *', '*const u8': 'const uint8_t *', '*const u64': 'const uint64_t *',
    '*mut u64': 'uint64_t *', '*mut u32': 'uint32_t *', '*mut usize': 'size_t *', 'u8': 'uint8_t', 'u32': 'uint32_t',
    'u64': 'uint64_t', 'i32': 'int32_t', 'i64': 'int64_t', 'f32': 'float', 'f64': 'double',
}
# `u32` parameters that are C enums, by parameter name; FUNCTION_PARAMS overrides per function.
ENUM_PARAMS = {'t': 'cl_type', 'ext': 'cl_ext', 'link': 'cl_linkage', 'flags': 'uint32_t'}
FUNCTION_PARAMS = {
    'cl_unary.op': 'cl_unop', 'cl_binary.op': 'cl_binop', 'cl_ovf.op': 'cl_ovfop',
    'cl_cast.op': 'cl_castop', 'cl_icmp.cc': 'cl_icmp_cc', 'cl_fcmp.cc': 'cl_fcmp_cc',
    'cl_atomic_rmw.op': 'cl_rmwop',
}
# Parameters that are a C `int`, and Rust names that are C keywords.
INT_PARAMS = {'writable', 'tls', 'signed'}
RENAME = {'default': 'dflt', 'signed': 'is_signed', 'new': 'repl', 'else': 'els', 'then': 'thn'}
LIMIT = 120


def functions(source):
    out = []
    pattern = re.compile(r'((?:[ \t]*///[^\n]*\n)*)[ \t]*#\[no_mangle\]\s*pub unsafe extern "C" fn (\w+)\((.*?)\)\s*(?:->\s*([^{]+?))?\s*\{', re.S)
    for m in pattern.finditer(source):
        docs = [re.sub(r'^\s*/// ?', '', line).rstrip() for line in m.group(1).splitlines()]
        out.append((m.group(2), [p.strip() for p in split_params(m.group(3)) if p.strip()], (m.group(4) or '').strip(), docs))
    return out


def split_params(text):
    return re.split(r',(?![^<>]*>)', text)


def c_type(fn, name, rust):
    key = f'{fn}.{name}'
    if key in FUNCTION_PARAMS:
        return FUNCTION_PARAMS[key]
    if name in INT_PARAMS:
        return 'int'
    if rust == 'u32' and name in ENUM_PARAMS:
        return ENUM_PARAMS[name]
    if rust not in TYPES:
        sys.exit(f'gen-header.py: {fn}: no C type for `{name}: {rust}`')
    return TYPES[rust]


def declaration(fn, params, ret, docs):
    args = []
    for p in params:
        name, rust = [s.strip() for s in p.split(':', 1)]
        ctype = c_type(fn, name, rust)
        args.append(ctype + ('' if ctype.endswith('*') else ' ') + RENAME.get(name, name))
    if not ret:
        result = 'void'
    elif ret == 'i32':
        result = 'int'
    elif ret in TYPES:
        result = TYPES[ret]
    else:
        sys.exit(f'gen-header.py: {fn}: no C type for the result `{ret}`')
    return result.rstrip(), args


def wrap(text, indent, width):
    words, lines, line = text.split(), [], ''
    for w in words:
        if line and len(line) + 1 + len(w) > width - indent:
            lines.append(line)
            line = w
        else:
            line = f'{line} {w}' if line else w
    return lines + ([line] if line else [])


def api(source):
    lines = ['/* Every function of the library: X(result, name, (parameters)). */', '#define CL_API(X) \\']
    for fn, params, ret, docs in functions(source):
        text = ' '.join(d for d in docs if d)
        if text:
            body = wrap(text, 5, LIMIT - 4)
            lines.append('  /* ' + body[0] + ('' if len(body) > 1 else ' */') + ' \\')
            for i, line in enumerate(body[1:], 1):
                lines.append('     ' + line + (' */' if i == len(body) - 1 else '') + ' \\')
        result, args = declaration(fn, params, ret, docs)
        head = f'  X({result}, {fn}, ('
        row = head
        cont = ' ' * len(head)
        for i, a in enumerate(args):
            piece = a + (', ' if i + 1 < len(args) else '')
            if len(row) + len(piece.rstrip()) + 5 > LIMIT and row.strip():
                lines.append(row.rstrip() + ' \\')
                row = cont
            row += piece
        lines.append(row + ')) \\')
    lines[-1] = lines[-1][:-2].rstrip()
    return '\n'.join(lines)


def aliases(source):
    return '\n'.join(f'#define {fn} cl_fns.fn_{fn}' for fn, *_ in functions(source))


def generate():
    source = (ROOT / 'src/lib.rs').read_text()
    template = (ROOT / 'include/cranelift.h.in').read_text()
    return BANNER + template.replace('@API@', api(source)).replace('@ALIASES@', aliases(source))


if __name__ == '__main__':
    header = generate()
    target = ROOT / 'include/cranelift.h'
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != header:
            sys.exit('include/cranelift.h is stale: run `python3 gen-header.py` and commit it')
    else:
        target.write_text(header)
